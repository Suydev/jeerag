/** Build an SVG element for an icon name. */
export function iconEl(name) {
  const tpl = document.createElement('template');
  tpl.innerHTML =
    `<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" ` +
    `stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${ICONS[name] || ''}</svg>`;
  return tpl.content.firstElementChild;
}

/** Replace every [data-icon] placeholder inside `root` with its SVG. */
export function hydrateIcons(root = document) {
  for (const holder of root.querySelectorAll('[data-icon]')) {
    if (holder.querySelector('svg')) continue;
    holder.prepend(iconEl(holder.dataset.icon));
    delete holder.dataset.icon;
  }
}

/** DOM builder: el('div', {class:'x', onclick: fn, text:'hi'}, child, child…) */
export function el(tag, attrs = {}, ...children) {
  const node = document.createElement(tag);
  for (const [k, v] of Object.entries(attrs || {})) {
    if (v == null || v === false) continue;
    if (k === 'class') node.className = v;
    else if (k === 'text') node.textContent = v;
    else if (k === 'html') node.innerHTML = v; // trusted: caller must pre-sanitize
    else if (k.startsWith('on') && typeof v === 'function') node.addEventListener(k.slice(2).toLowerCase(), v);
    else if (v === true) node.setAttribute(k, '');
    else node.setAttribute(k, String(v));
  }
  for (const c of children.flat(Infinity)) {
    if (c == null || c === false) continue;
    node.append(c.nodeType ? c : document.createTextNode(String(c)));
  }
  return node;
}

/** Escape a string for safe interpolation into innerHTML. */
export const esc = (s) =>
  String(s).replace(/[&<>"']/g, (c) =>
    ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));

/** Clipboard write with a legacy fallback. Returns true on success. */
export async function copyText(text) {
  try {
    await navigator.clipboard.writeText(text);
    return true;
  } catch {
    try {
      const ta = document.createElement('textarea');
      ta.value = text;
      ta.style.cssText = 'position:fixed;opacity:0';
      document.body.append(ta);
      ta.select();
      const ok = document.execCommand('copy');
      ta.remove();
      return ok;
    } catch {
      return false;
    }
  }
}

/**
 * Stack of open overlays (modals, drawer, palette, page viewer).
 * Each close function registers itself and removes itself when run,
 * so the global Escape handler can always close just the topmost one.
 */
export const overlayStack = {
  arr: [],
  push(fn) { this.arr.push(fn); },
  remove(fn) {
    const i = this.arr.indexOf(fn);
    if (i >= 0) this.arr.splice(i, 1);
  },
  top() { return this.arr[this.arr.length - 1] || null; },
};

/** Animated count-up for number text content. */
export function countUp(node, target, { duration = 700, format } = {}) {
  const fmt = format || ((n) => Math.round(n).toLocaleString('en-US'));
  const t0 = performance.now();
  const tick = (t) => {
    const p = Math.min(1, (t - t0) / duration);
    const eased = 1 - Math.pow(1 - p, 3);
    node.textContent = fmt(target * eased);
    if (p < 1) requestAnimationFrame(tick);
  };
  requestAnimationFrame(tick);
}
